#!/usr/bin/env python3
"""shiroikuma-kakutoku fork: rebuild every translation file from an upstream tag.

    python3 tool/sk_translations.py v1.7.5

Translations are rebuilt on every upstream sync, never merged by hand:

* each locale is upstream's file of the given tag, with "Obtainium" replaced by
  the fork's name in the values;
* the fork's own strings come from tool/sk_strings/en.json — every locale gets
  them in English, because upstream's translation_shape_test fails when a
  locale lacks a key that en.json has. A key of that file which upstream has
  too is a rewording, and applies to en.json only;
* ja.json then takes everything in tool/sk_strings/ja.json: the Japanese of
  the fork's strings, and of the upstream strings upstream's own Japanese file
  leaves in English.

The same catalogue is written to lib/sk_strings.dart (the SkStr names and the
English every "sk…" key falls back to when no translation is loaded), so the
code and the translation files cannot drift apart.

Format of the JSON: four-space indent, ensure_ascii=False, a final newline.
"""
import json
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = 'assets/translations'
UPSTREAM_NAME = 'Obtainium'
FORK_NAME = '白い熊 獲得'


def git(*args):
    return subprocess.check_output(['git', '-C', REPO, *args])


def load(path):
    with open(os.path.join(REPO, path), encoding='utf-8') as f:
        return json.load(f)


def rebrand(value):
    if isinstance(value, str):
        return value.replace(UPSTREAM_NAME, FORK_NAME)
    if isinstance(value, dict):
        return {k: rebrand(v) for k, v in value.items()}
    return value


def insert_sorted(pairs, key, value):
    """Puts a new key before the first key that sorts after it."""
    low = key.lower()
    for i, (k, _) in enumerate(pairs):
        if k.lower() > low:
            pairs.insert(i, (key, value))
            return
    pairs.append((key, value))


def build(upstream, fork_en, fork_ja, locale):
    pairs = [(k, rebrand(v)) for k, v in upstream.items()]
    have = {k for k, _ in pairs}
    for key, value in fork_en.items():
        if key in have:
            if locale == 'en':
                pairs = [(k, value if k == key else v) for k, v in pairs]
        else:
            insert_sorted(pairs, key, value)
            have.add(key)
    if locale == 'ja':
        missing = set(fork_ja) - have
        if missing:
            sys.exit(f'ja.json names keys that do not exist: {sorted(missing)}')
        pairs = [(k, fork_ja.get(k, v)) for k, v in pairs]
    return dict(pairs)


def dart_string(text):
    for plain, escaped in (('\\', '\\\\'), ("'", "\\'"), ('$', '\\$'), ('\n', '\\n')):
        text = text.replace(plain, escaped)
    return f"'{text}'"


def write_dart(fork_en):
    sk = {k: v for k, v in fork_en.items() if k.startswith('sk')}
    names = [k[len('skStr_'):] for k in sk if k.startswith('skStr_')]
    lines = [
        '// shiroikuma-kakutoku fork: the fork\'s own user-visible strings.',
        '//',
        '// GENERATED by tool/sk_translations.py from tool/sk_strings/en.json —',
        '// edit the catalogue and run the tool, never this file.',
        '',
        "import 'package:easy_localization/easy_localization.dart';",
        '',
        '/// The translation of [key], or its English when no translation is',
        '/// loaded (a headless engine, a test).',
        'String skTr(String key, [List<String>? args]) {',
        '  if (trExists(key)) return tr(key, args: args);',
        '  var text = skEnglish[key] ?? key;',
        '  for (final arg in args ?? const <String>[]) {',
        "    text = text.replaceFirst('{}', arg);",
        '  }',
        '  return text;',
        '}',
        '',
        '/// The loose strings of the fork\'s own screens.',
        'enum SkStr {',
        *[f'  {n},' for n in names[:-1]],
        f'  {names[-1]};',
        '',
        '  /// The translated string.',
        "  String get t => skTr('skStr_$name');",
        '',
        '  /// The translated string with each {} filled from [args].',
        "  String f(List<String> args) => skTr('skStr_$name', args);",
        '}',
        '',
        '/// The English of every key the fork adds.',
        'const Map<String, String> skEnglish = {',
        *[f'  {dart_string(k)}: {dart_string(v)},' for k, v in sk.items()],
        '};',
        '',
    ]
    path = os.path.join(REPO, 'lib/sk_strings.dart')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    # Formatted like the rest of lib/, so a rerun leaves no diff.
    dart = os.path.expanduser('~/flutter/bin/dart')
    if os.path.exists(dart):
        subprocess.run([dart, 'format', path], check=True, stdout=subprocess.DEVNULL)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    tag = sys.argv[1]
    fork_en = load('tool/sk_strings/en.json')
    fork_ja = load('tool/sk_strings/ja.json')
    untranslated = [k for k in fork_en if k not in fork_ja and k != 'appName']
    if untranslated:
        sys.exit(f'no Japanese for: {untranslated}')
    files = git('ls-tree', '--name-only', tag, DIR + '/').decode().split()
    for path in files:
        # package.json and its lock file live beside the locales.
        if not path.endswith('.json') or os.path.basename(path).startswith('package'):
            continue
        locale = os.path.basename(path)[:-len('.json')]
        upstream = json.loads(git('show', f'{tag}:{path}'))
        result = build(upstream, fork_en, fork_ja, locale)
        with open(os.path.join(REPO, path), 'w', encoding='utf-8') as f:
            json.dump(result, f, ensure_ascii=False, indent=4)
            f.write('\n')
    write_dart(fork_en)
    print(f'locales rebuilt from {tag}; lib/sk_strings.dart written')


if __name__ == '__main__':
    main()
